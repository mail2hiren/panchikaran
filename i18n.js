  // Devanagari -> Gujarati: the two Unicode blocks are aligned (offset 0x180).
  function toGujarati(s) {
    var out = '';
    for (var i = 0; i < s.length; i++) {
      var c = s.charCodeAt(i);
      if (c >= 0x0901 && c <= 0x0963 && c !== 0x0964 && c !== 0x0965) out += String.fromCharCode(c + 0x180);
      else if (c === 0x0950) out += 'ૐ';
      else if (c >= 0x0966 && c <= 0x096F) out += String.fromCharCode(c + 0x180);
      else out += s[i];
    }
    return out;
  }

